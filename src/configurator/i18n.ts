const dict: Record<Lang, CUi> = { tr, en, ru, ar };
export const useCUi = (lang: Lang): CUi => dict[lang];

export const trailerName = (t: CUi, id: TrailerId) => t[`t_${id}` as keyof CUi];
export const trailerDesc = (t: CUi, id: TrailerId) => t[`t_${id}_d` as keyof CUi];
export const socketName = (t: CUi, id: SocketId) => t[(id === '7x2' ? 's_7x2' : id === '15' ? 's_15' : 's_7x2_15') as keyof CUi];
export const categoryName = (t: CUi, id: CategoryId) => t[`cat_${id}` as keyof CUi];
export const summaryLabel = (t: CUi, id: CategoryId) => t[`sum_${id}` as keyof CUi];
